def escape_xml(text):
    return str(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def pdf_escape(text):
    return str(text).replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def hex_to_rgb(color):
    color = color.lstrip("#")
    return tuple(int(color[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def make_plot_payload(series, x_label, y_label, title, refs=None, scatter=False):
    xs = [x for item in series for x, _ in item["points"]]
    ys = [y for item in series for _, y in item["points"]]
    if refs:
        ys.extend(value for value, _ in refs)
    xmin, xmax = min(xs), max(xs)
    ymin, ymax = min(ys), max(ys)
    if xmax <= xmin:
        xmax = xmin + 1.0
    if ymax <= ymin:
        ymax = ymin + 1.0
    xpad = 0.05 * (xmax - xmin)
    ypad = 0.10 * (ymax - ymin)
    return {
        "series": series,
        "x_label": x_label,
        "y_label": y_label,
        "title": title,
        "refs": refs or [],
        "scatter": scatter,
        "xmin": xmin - xpad,
        "xmax": xmax + xpad,
        "ymin": max(0.0, ymin - ypad) if ymin >= 0.0 else ymin - ypad,
        "ymax": ymax + ypad,
    }


def write_svg_plot(path, payload, width=720, height=480):
    left, right, top, bottom = 80.0, 28.0, 52.0, 68.0
    pw, ph = width - left - right, height - top - bottom

    def px(x):
        return left + (x - payload["xmin"]) / (payload["xmax"] - payload["xmin"]) * pw

    def py(y):
        return top + (payload["ymax"] - y) / (payload["ymax"] - payload["ymin"]) * ph

    out = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">' % (width, height, width, height),
        '<rect width="100%%" height="100%%" fill="white"/>',
        '<style>text{font-family:Arial,Helvetica,sans-serif;fill:#222}.tick{font-size:11px}.label{font-size:13px}.title{font-size:17px;font-weight:600}.legend{font-size:11px}</style>',
        '<text class="title" x="%g" y="27" text-anchor="middle">%s</text>' % (width / 2.0, escape_xml(payload["title"])),
    ]
    for idx in range(6):
        xv = payload["xmin"] + idx * (payload["xmax"] - payload["xmin"]) / 5.0
        yv = payload["ymin"] + idx * (payload["ymax"] - payload["ymin"]) / 5.0
        out.append('<line x1="%g" y1="%g" x2="%g" y2="%g" stroke="#e6e6e6"/>' % (px(xv), top, px(xv), top + ph))
        out.append('<line x1="%g" y1="%g" x2="%g" y2="%g" stroke="#e6e6e6"/>' % (left, py(yv), left + pw, py(yv)))
        out.append('<text class="tick" x="%g" y="%g" text-anchor="middle">%.3g</text>' % (px(xv), top + ph + 20, xv))
        out.append('<text class="tick" x="%g" y="%g" text-anchor="end">%.3g</text>' % (left - 8, py(yv) + 4, yv))
    out.append('<line x1="%g" y1="%g" x2="%g" y2="%g" stroke="#222" stroke-width="1.4"/>' % (left, top + ph, left + pw, top + ph))
    out.append('<line x1="%g" y1="%g" x2="%g" y2="%g" stroke="#222" stroke-width="1.4"/>' % (left, top, left, top + ph))
    for value, label in payload["refs"]:
        out.append('<line x1="%g" y1="%g" x2="%g" y2="%g" stroke="#555" stroke-dasharray="6,4"/>' % (left, py(value), left + pw, py(value)))
        out.append('<text class="legend" x="%g" y="%g" text-anchor="end">%s</text>' % (left + pw - 4, py(value) - 4, escape_xml(label)))
    for idx, item in enumerate(payload["series"]):
        color = item.get("color", COLORS[idx % len(COLORS)])
        coords = " ".join("%g,%g" % (px(x), py(y)) for x, y in item["points"])
        if not payload["scatter"]:
            out.append('<polyline points="%s" fill="none" stroke="%s" stroke-width="2.2"/>' % (coords, color))
        for x, y in item["points"]:
            out.append('<circle cx="%g" cy="%g" r="3.2" fill="%s"/>' % (px(x), py(y), color))
        lx = left + 12 + (idx % 3) * 190
        ly = top + 16 + (idx // 3) * 18
        out.append('<line x1="%g" y1="%g" x2="%g" y2="%g" stroke="%s" stroke-width="2.2"/>' % (lx, ly - 4, lx + 20, ly - 4, color))
        out.append('<text class="legend" x="%g" y="%g">%s</text>' % (lx + 25, ly, escape_xml(item["label"])))
    out.append('<text class="label" x="%g" y="%g" text-anchor="middle">%s</text>' % (left + pw / 2.0, height - 18, escape_xml(payload["x_label"])))
    out.append('<text class="label" transform="translate(18,%g) rotate(-90)" text-anchor="middle">%s</text>' % (top + ph / 2.0, escape_xml(payload["y_label"])))
    out.append('</svg>')
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def write_pdf_plot(path, payload, width=720, height=480):
    left, right, top, bottom = 80.0, 28.0, 52.0, 68.0
    pw, ph = width - left - right, height - top - bottom

    def px(x):
        return left + (x - payload["xmin"]) / (payload["xmax"] - payload["xmin"]) * pw

    def py(y):
        return bottom + (y - payload["ymin"]) / (payload["ymax"] - payload["ymin"]) * ph

    commands = ["1 1 1 rg 0 0 %d %d re f" % (width, height), "0 0 0 RG 0 0 0 rg"]

    def text_cmd(x, y, size, value):
        commands.append("BT /F1 %g Tf %g %g Td (%s) Tj ET" % (size, x, y, pdf_escape(value)))

    text_cmd(width / 2.0 - 120.0, height - 28.0, 16, payload["title"])
    for idx in range(6):
        xv = payload["xmin"] + idx * (payload["xmax"] - payload["xmin"]) / 5.0
        yv = payload["ymin"] + idx * (payload["ymax"] - payload["ymin"]) / 5.0
        commands.append("0.9 0.9 0.9 RG 0.5 w %g %g m %g %g l S" % (px(xv), bottom, px(xv), bottom + ph))
        commands.append("0.9 0.9 0.9 RG 0.5 w %g %g m %g %g l S" % (left, py(yv), left + pw, py(yv)))
        commands.append("0 0 0 RG")
        text_cmd(px(xv) - 13.0, bottom - 18.0, 9, "%.3g" % xv)
        text_cmd(left - 45.0, py(yv) - 3.0, 9, "%.3g" % yv)
    commands.append("0 0 0 RG 1.2 w %g %g m %g %g l S" % (left, bottom, left + pw, bottom))
    commands.append("0 0 0 RG 1.2 w %g %g m %g %g l S" % (left, bottom, left, bottom + ph))
    for value, label in payload["refs"]:
        yy = py(value)
        commands.append("0.35 0.35 0.35 RG [6 4] 0 d %g %g m %g %g l S [] 0 d" % (left, yy, left + pw, yy))
        text_cmd(left + pw - 92.0, yy + 4.0, 9, label)
    for idx, item in enumerate(payload["series"]):
        color = item.get("color", COLORS[idx % len(COLORS)])
        r, g, b = hex_to_rgb(color)
        commands.append("%g %g %g RG %g %g %g rg 2 w" % (r, g, b, r, g, b))
        if not payload["scatter"] and item["points"]:
            x0, y0 = item["points"][0]
            commands.append("%g %g m" % (px(x0), py(y0)))
            for x, y in item["points"][1:]:
                commands.append("%g %g l" % (px(x), py(y)))
            commands.append("S")
        for x, y in item["points"]:
            commands.append("%g %g 5 5 re f" % (px(x) - 2.5, py(y) - 2.5))
        lx = left + 12 + (idx % 3) * 190
        ly = bottom + ph - 16 - (idx // 3) * 17
        commands.append("%g %g m %g %g l S" % (lx, ly, lx + 20, ly))
        commands.append("0 0 0 rg")
        text_cmd(lx + 25, ly - 3, 9, item["label"])
    commands.append("0 0 0 rg")
    text_cmd(left + pw / 2.0 - 45.0, 18.0, 11, payload["x_label"])
    text_cmd(8.0, bottom + ph / 2.0, 10, payload["y_label"])
    stream = ("\n".join(commands) + "\n").encode("ascii", "replace")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        ("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %d %d] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>" % (width, height)).encode("ascii"),
        b"<< /Length " + str(len(stream)).encode("ascii") + b" >>\nstream\n" + stream + b"endstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    blob = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for index, obj in enumerate(objects, start=1):
        offsets.append(len(blob))
        blob.extend(("%d 0 obj\n" % index).encode("ascii"))
        blob.extend(obj)
        blob.extend(b"\nendobj\n")
    xref = len(blob)
    blob.extend(("xref\n0 %d\n" % (len(objects) + 1)).encode("ascii"))
    blob.extend(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        blob.extend(("%010d 00000 n \n" % offset).encode("ascii"))
    blob.extend(("trailer << /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objects) + 1, xref)).encode("ascii"))
    path.write_bytes(bytes(blob))


