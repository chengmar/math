def metrics(cases):
    return {
        "max_draft_m": max(c["draft_m"] for c in cases),
        "max_drum_angle_deg": max(c["drum_angle_deg"] for c in cases),
        "max_anchor_angle_deg": max(c["chain"]["anchor_angle_deg"] for c in cases),
        "max_wander_radius_m": max(c["wander_radius_m"] for c in cases),
    }


def find_min_ball_for_design(chain_type, chain_length, stress_factor=1.10):
    last_mass = 500.0
    last_ratio = float("inf")
    bracket = None
    for mass in [500.0 + 400.0 * i for i in range(13)]:
        design = {"chain_type": chain_type, "chain_length_m": chain_length, "ball_mass_kg": mass}
        try:
            cases = screening_envelope(design, horizontal_factor=stress_factor)
            ratio = max(case_constraint_ratio(c) for c in cases)
            draft_ok = max(c["draft_m"] for c in cases) < 2.0
        except InfeasibleError:
            ratio = float("inf")
            draft_ok = False
        if ratio <= 1.0 and draft_ok:
            bracket = (last_mass, mass)
            break
        last_mass = mass
        last_ratio = ratio
    if bracket is None:
        return None

    def margin(mass):
        design = {"chain_type": chain_type, "chain_length_m": chain_length, "ball_mass_kg": mass}
        try:
            cases = screening_envelope(design, horizontal_factor=stress_factor)
        except InfeasibleError:
            return 1.0e6
        return max(case_constraint_ratio(c) for c in cases) - 1.0

    lo, hi = bracket
    if margin(lo) <= 0.0:
        threshold = lo
    else:
        threshold = bisect_root(margin, lo, hi, iterations=18, tol=1.0e-5)
    recommended = round_up(threshold, 50.0)
    design = {"chain_type": chain_type, "chain_length_m": chain_length, "ball_mass_kg": recommended}
    stressed_cases = screening_envelope(design, horizontal_factor=stress_factor)
    nominal_cases = screening_envelope(design, horizontal_factor=1.0)
    if max(case_constraint_ratio(c) for c in stressed_cases) > 1.0 + 1.0e-7:
        return None
    return {
        "chain_type": chain_type,
        "link_count": int(round(chain_length / CHAIN_TYPES[chain_type]["link_length_m"])),
        "chain_length_m": chain_length,
        "chain_dry_mass_kg": chain_length * CHAIN_TYPES[chain_type]["linear_mass_kg_m"],
        "continuous_ball_threshold_kg": threshold,
        "ball_mass_kg": recommended,
        "stress_factor": stress_factor,
        "nominal": metrics(nominal_cases),
        "stressed": metrics(stressed_cases),
    }


def pareto_front(rows):
    objectives = ("max_draft_m", "max_drum_angle_deg", "max_wander_radius_m")
    front = []
    for i, row in enumerate(rows):
        dominated = False
        ai = row["nominal"]
        for j, other in enumerate(rows):
            if i == j:
                continue
            aj = other["nominal"]
            no_worse = all(aj[key] <= ai[key] + 1.0e-12 for key in objectives)
            strictly = any(aj[key] < ai[key] - 1.0e-12 for key in objectives)
            if no_worse and strictly:
                dominated = True
                break
        if not dominated:
            front.append(row)
    return front


def select_knee(front):
    # Fixed, problem-defined scales avoid allowing a very narrow observed range
    # (for example a few hundredths of a degree) to dominate metres of wander.
    scales = {"max_draft_m": 2.0, "max_drum_angle_deg": 5.0,
              "max_wander_radius_m": 20.0}
    best = None
    best_score = float("inf")
    for row in front:
        components = [row["nominal"][key] / scale for key, scale in scales.items()]
        score = math.sqrt(sum(value * value for value in components))
        row["compromise_score"] = score
        if score < best_score - 1.0e-12:
            best_score = score
            best = row
        elif abs(score - best_score) <= 1.0e-12:
            tie_new = (row["chain_dry_mass_kg"], row["chain_length_m"], row["ball_mass_kg"])
            tie_old = (best["chain_dry_mass_kg"], best["chain_length_m"], best["ball_mass_kg"])
            if tie_new < tie_old:
                best = row
    return best


