"""Blind, deterministic solver for CUMCM 2016A (mooring-system design).

Only Python's standard library is used.  The script implements

1. a lumped single-link baseline;
2. a segmented rigid-link + massless straight-chain candidate; and
3. the selected segmented rigid-link + weighted catenary model.

All reported numbers and figures are regenerated by ``python code/solve.py``.
"""

